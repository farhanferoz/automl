"""GPU-native builds of the libraries listed in scripts/gpu_builds.toml, as a standing part of the environment.

    python3 scripts/gpu_builds.py configure            # before `uv sync`: render the machine's uv configuration
    python3 scripts/gpu_builds.py stale --venv .venv   # before it: uv flags rebuilding packages installed without this GPU's code
    python3 scripts/gpu_builds.py check --venv .venv   # after it: fail loudly if a listed package lacks this GPU's code

`configure` writes the user-level uv configuration ($XDG_CONFIG_HOME/uv/uv.toml, default ~/.config/uv/uv.toml), which uv
merges into every project's settings on this machine: each listed package is built from its source release
(`no-binary-package`) with the listed build settings (`config-settings-package`), so every `uv sync` (install.sh, the
weekly upgrade, a hand-run sync) builds the locked version for this GPU, and a new locked version is rebuilt by the next
sync. A sync without those settings would put the published wheel back (measured 2026-11-06), which is why they live in the
machine's configuration and not on one command line. On a machine without an NVIDIA GPU it writes nothing.

The file is generated: it starts with GENERATED_MARKER, and a uv.toml without that line is never overwritten.
Standard library only (it runs before the project's environment exists).
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.request
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

REGISTRY = Path(__file__).with_name("gpu_builds.toml")
GENERATED_MARKER = "# GENERATED by automl scripts/gpu_builds.py from scripts/gpu_builds.toml: edit that file, then rerun configure."
PYPI_JSON = "https://pypi.org/pypi/{package}/json"
CUDA_ROOTS = (Path("/usr/local/cuda"),)  # searched after PATH for nvcc
NCCL_SUBDIR = Path("nvidia/nccl")
NCCL_LIBRARY_NAME = "libnccl.so.2"


class Command(StrEnum):
    """The subcommands."""

    CONFIGURE = "configure"
    STALE = "stale"
    CHECK = "check"


def log(message: str) -> None:
    """Every decision is printed, with the reason (on stderr: `stale` prints flags on stdout)."""
    print(f"[gpu-builds] {message}", file=sys.stderr, flush=True)


@dataclass(frozen=True)
class Gpu:
    """The machine's GPU and CUDA toolkit, as the build settings need them."""

    compute_capability: str  # e.g. "12.1"
    cuda_major: int  # the toolkit's major version, e.g. 13

    @property
    def sm(self) -> str:
        """The architecture digits, e.g. "121"."""
        return self.compute_capability.replace(".", "")

    @property
    def cuda_archs(self) -> str:
        """Native code for this GPU plus PTX for its successors, as a CMake architecture list."""
        return f"{self.sm}-real;{self.sm}-virtual"


def detect_gpu() -> Gpu | None:
    """The first NVIDIA GPU and the CUDA toolkit, or None when the machine has no NVIDIA GPU."""
    smi = shutil.which("nvidia-smi")
    if smi is None:
        log("no nvidia-smi on PATH: no NVIDIA GPU, published wheels are kept")
        return None
    query = subprocess.run([smi, "--query-gpu=compute_cap", "--format=csv,noheader"], capture_output=True, text=True, check=False)
    capabilities = [line.strip() for line in query.stdout.splitlines() if line.strip()]
    if query.returncode != 0 or not capabilities:
        log(f"nvidia-smi lists no GPU (exit {query.returncode}): published wheels are kept")
        return None
    if len(set(capabilities)) > 1:
        raise SystemExit(f"[gpu-builds] GPUs of different compute capability {sorted(set(capabilities))}: build settings for one GPU type only")
    nvcc = shutil.which("nvcc") or next((str(root / "bin" / "nvcc") for root in CUDA_ROOTS if (root / "bin" / "nvcc").exists()), None)
    if nvcc is None:
        raise SystemExit("[gpu-builds] an NVIDIA GPU is present but no CUDA toolkit (nvcc) was found: install the CUDA toolkit, then rerun")
    version = re.search(r"release (\d+)\.(\d+)", subprocess.run([nvcc, "--version"], capture_output=True, text=True, check=True).stdout)
    if version is None:
        raise SystemExit(f"[gpu-builds] could not read the CUDA version from {nvcc} --version")
    gpu = Gpu(compute_capability=capabilities[0], cuda_major=int(version.group(1)))
    log(f"GPU compute capability {gpu.compute_capability} (architectures {gpu.cuda_archs}); CUDA toolkit {version.group(1)}.{version.group(2)} at {nvcc}")
    return gpu


def load_registry() -> dict:
    """The registry, with its build root expanded."""
    with REGISTRY.open("rb") as handle:
        registry = tomllib.load(handle)
    registry["build_root"] = Path(registry["build_root"]).expanduser()
    return registry


def latest_version(package: str) -> str:
    """The newest release on PyPI (the machine rule: latest versions)."""
    with urllib.request.urlopen(PYPI_JSON.format(package=package), timeout=30) as response:
        return json.load(response)["info"]["version"]


def ensure_nccl(registry: dict, gpu: Gpu) -> dict[str, str]:
    """A build-time NCCL under the build root (installed once per version); the placeholders that point at it."""
    package = registry["nccl"]["package"].format(cuda_major=gpu.cuda_major)
    version = latest_version(package)
    target = registry["build_root"] / "nccl" / f"{package}-{version}"
    root = target / NCCL_SUBDIR
    if (root / "lib" / NCCL_LIBRARY_NAME).exists():
        log(f"build-time NCCL {package}=={version} already at {target}")
    else:
        log(f"installing build-time NCCL {package}=={version} into {target}")
        subprocess.run(["uv", "pip", "install", "--quiet", "--no-deps", "--python", sys.executable, "--target", str(target), f"{package}=={version}"], check=True)
    if not (root / "include" / "nccl.h").exists() or not (root / "lib" / NCCL_LIBRARY_NAME).exists():
        raise SystemExit(f"[gpu-builds] {target} lacks nccl.h or {NCCL_LIBRARY_NAME}: the {package} layout changed; fix ensure_nccl")
    return {"nccl_include": str(root / "include"), "nccl_lib": str(root / "lib" / NCCL_LIBRARY_NAME), "nccl_lib_dir": str(root / "lib")}


def uv_config_path() -> Path:
    """The user-level configuration file of uv."""
    return Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "uv" / "uv.toml"


def toml_string(value: str) -> str:
    """A TOML basic string (JSON's escaping is valid TOML for these values)."""
    return json.dumps(value)


def render(registry: dict, gpu: Gpu) -> str:
    """The uv configuration for this machine."""
    values = {"cuda_archs": gpu.cuda_archs}
    packages = registry["packages"]
    if any(spec.get("needs_nccl") for spec in packages.values()):
        values |= ensure_nccl(registry, gpu)
    lines = [GENERATED_MARKER, f"# GPU compute capability {gpu.compute_capability}, CUDA {gpu.cuda_major}.", ""]
    lines.append("no-binary-package = [" + ", ".join(toml_string(name) for name in packages) + "]")
    for name, spec in packages.items():
        lines += ["", f"[config-settings-package.{name}]"]
        lines += [f"{toml_string(key)} = {toml_string(value.format(**values))}" for key, value in spec["settings"].items()]
        log(f"{name}: built from source on every sync with {len(spec['settings'])} settings for compute capability {gpu.compute_capability}")
    return "\n".join(lines) + "\n"


def configure() -> int:
    """Write (or leave alone) the machine's uv configuration."""
    gpu = detect_gpu()
    path = uv_config_path()
    if gpu is None:
        return 0
    if path.exists() and GENERATED_MARKER not in path.read_text():
        raise SystemExit(f"[gpu-builds] {path} exists and was not generated by this script: merge its settings into scripts/gpu_builds.toml's output by hand")
    text = render(load_registry(), gpu)
    if path.exists() and path.read_text() == text:
        log(f"{path} already up to date")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    log(f"wrote {path}")
    return 0


def native_library(venv: Path, spec: dict) -> Path | None:
    """A registered package's compiled library inside `venv`, or None when the package is not installed there."""
    found = sorted(venv.glob(f"lib/python3*/site-packages/{spec['native_library']}"))
    return found[0] if found else None


def lacks_gpu_code(venv: Path, gpu: Gpu) -> list[str]:
    """The registered packages installed in `venv` whose compiled library has no code for this GPU (e.g. the published wheel)."""
    stale = []
    for name, spec in load_registry()["packages"].items():
        library = native_library(venv, spec)
        if library is not None and f"sm_{gpu.sm}".encode() not in library.read_bytes():
            stale.append(name)
    return stale


def stale(venv: Path) -> int:
    """Print the uv flags that rebuild the registered packages in `venv` lacking this GPU's code (uv keeps an installed version)."""
    gpu = detect_gpu()
    names = lacks_gpu_code(venv, gpu) if gpu is not None and venv.exists() else []
    for name in names:
        log(f"{name}: installed without sm_{gpu.sm} code, so this sync rebuilds it from source")
    print(" ".join(f"--reinstall-package {name}" for name in names))
    return 0


def check(venv: Path) -> int:
    """Each registered package installed in `venv` carries native code for this GPU and imports; non-zero otherwise."""
    gpu = detect_gpu()
    if gpu is None:
        return 0
    python = venv / "bin" / "python"
    without_code = set(lacks_gpu_code(venv, gpu))
    failures = []
    for name, spec in load_registry()["packages"].items():
        if native_library(venv, spec) is None:
            log(f"{name}: not installed in {venv}, nothing to check")
            continue
        environment = {key: value for key, value in os.environ.items() if key != "LD_LIBRARY_PATH"}
        imported = subprocess.run([str(python), "-c", f"import {name}"], capture_output=True, text=True, env=environment, check=False)
        log(f"{name}: native code for sm_{gpu.sm}: {name not in without_code}; imports without LD_LIBRARY_PATH: {imported.returncode == 0}")
        if name in without_code or imported.returncode != 0:
            failures.append(f"{name} ({'no sm_' + gpu.sm + ' code' if name in without_code else imported.stderr.strip().splitlines()[-1]})")
    if failures:
        log(f"FAILED in {venv}: {'; '.join(failures)}. Remedy: rebuild the environment with ./install.sh, which configures uv and "
            "rebuilds these packages (a sync run without the machine's uv configuration installs the published wheel)")
        return 1
    return 0


def main() -> int:
    """Command line."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser(Command.CONFIGURE.value, help="render the machine's uv configuration (before uv sync)")
    for command, text in ((Command.STALE, "print the uv flags that rebuild packages lacking this GPU's code (before uv sync)"),
                          (Command.CHECK, "verify an environment's builds (after uv sync)")):
        commands.add_parser(command.value, help=text).add_argument("--venv", type=Path, required=True)
    arguments = parser.parse_args()
    command = Command(arguments.command)
    if command is Command.CONFIGURE:
        return configure()
    return (stale if command is Command.STALE else check)(arguments.venv.resolve())


if __name__ == "__main__":
    sys.exit(main())
